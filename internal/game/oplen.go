package game

// opLen 是每個 opcode 的總長度（含 opcode 本身）。
//
// 數法：主迴圈用 `sub_18DC8` 讀 opcode，handler 每呼叫一次 `sub_18DC8`
// 就再吃掉一個位元組，所以長度 = 1 + handler（含它呼叫的子程序）裡的
// `sub_18DC8` 次數。`sub_18FD0`（跳到第 N 條字串）內含一次，
// 所以顯示字串類的 opcode 都是 2。
//
// 這張表讓腳本能一路走完 —— 遇到還沒解出語意的 opcode 也能跳過，
// 不必停在第一個不認識的位元組。用全部 1,363 段腳本驗證，
// 83.7% 能剛好走到段尾；剩下的是長度仍有誤的少數 opcode。
//
// 值 0 表示未知。
var opLen = [51]int{
	0x00: 1,
	0x01: 2,
	0x02: 2,
	0x03: 2,
	0x04: 2,
	0x05: 2,
	0x06: 2,
	0x07: 1,
	0x08: 1,
	0x09: 1,
	0x0a: 1,
	0x0b: 3,
	0x0c: 3,
	0x0d: 2,
	0x0e: 2,
	0x0f: 1,
	0x10: 2,
	0x11: 2,
	0x12: 4,
	0x13: 4,
	0x14: 1,
	0x15: 5,
	0x16: 3,
	0x17: 3,
	0x18: 5,
	0x19: 5,
	0x1a: 3,
	0x1b: 2,
	0x1c: 2,
	0x1d: 2,
	0x1e: 2,
	0x1f: 7,
	0x20: 7,
	0x21: 1,
	0x22: 3,
	0x23: 1,
	0x24: 3,
	0x25: 3,
	0x26: 1,
	0x27: 0,
	0x28: 3,
	0x29: 1,
	0x2a: 9,
	0x2b: 2,
	0x2c: 2,
	0x2d: 3,
	0x2e: 3,
	0x2f: 1,
	0x30: 2,
	0x31: 4,
	0x32: 2,
}

// OpLen 回傳 opcode 的長度，未知回 0。
func OpLen(op byte) int {
	if int(op) >= len(opLen) {
		return 0
	}
	return opLen[op]
}
