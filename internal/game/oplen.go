package game

// opLen 是每個 opcode 的總長度（含 opcode 本身）。
//
// 兩個來源合起來才對得上。先從程式碼數：主迴圈用 `sub_18DC8` 讀 opcode，
// handler 每呼叫一次 `sub_18DC8` 就再吃掉一個位元組，所以長度 =
// 1 + handler（含它呼叫的子程序）裡的 `sub_18DC8` 次數。這樣數出來的表
// 讓 1,363 段腳本裡 83.7% 剛好走到段尾。
//
// 漏掉的是**迴圈與條件分支**：靜態數呼叫點看不出 `sub_19912`（opcode 0x12）
// 那個 `cmp si, 0Ah / jl` 會讀十個位元組。剩下的 16% 由資料補齊 ——
// 每段腳本必須恰好走到段尾，這條約束把八個 opcode 的長度定了下來，
// **全部 1,363 段 100% 走完**。
//
// 兩邊對得起來：擬合說 0x12 是 13，回頭讀 `sub_19912` 正是
// 「迴圈讀 10 個 + `byte_10415 == 0x80` 時再讀 2 個」= 1+10+2。
//
// 值 0 表示未知。
var opLen = [51]int{
	0x00: 1,
	0x01: 2,
	0x02: 2,
	0x03: 2,
	0x04: 2,
	0x05: 2,
	0x06: 2,
	0x07: 1,
	0x08: 1,
	0x09: 1,
	0x0a: 1,
	0x0b: 3,
	0x0c: 3,
	0x0d: 2,
	0x0e: 2,
	0x0f: 1,
	0x10: 2,
	0x11: 2,
	0x12: 13,  // 迴圈／條件分支，靜態計數少算了
	0x13: 11,  // 迴圈／條件分支，靜態計數少算了
	0x14: 1,
	0x15: 4,  // 迴圈／條件分支，靜態計數少算了
	0x16: 3,
	0x17: 3,
	0x18: 5,
	0x19: 5,
	0x1a: 3,
	0x1b: 2,
	0x1c: 2,
	0x1d: 2,
	0x1e: 2,
	0x1f: 7,
	0x20: 7,
	0x21: 4,  // 迴圈／條件分支，靜態計數少算了
	0x22: 3,
	0x23: 3,  // 迴圈／條件分支，靜態計數少算了
	0x24: 3,
	0x25: 3,
	0x26: 1,
	0x27: 1,  // 迴圈／條件分支，靜態計數少算了
	0x28: 3,
	0x29: 1,
	0x2a: 10,  // 迴圈／條件分支，靜態計數少算了
	0x2b: 2,
	0x2c: 2,
	0x2d: 3,
	0x2e: 3,
	0x2f: 12,  // 迴圈／條件分支，靜態計數少算了
	0x30: 2,
	0x31: 4,
	0x32: 2,
}

// OpLen 回傳 opcode 的長度，未知回 0。
func OpLen(op byte) int {
	if int(op) >= len(opLen) {
		return 0
	}
	return opLen[op]
}
