// 「1/ L」是「以施法者經驗等級計算」、「2 SP＋1寶石」是法力加寶石。
//
// **這是手冊給的規格，不是從程式碼解出來的。** 實際的數值判定
// （傷害、命中、抗性）還沒從 overlay 讀出來，所以這張表現在的用途是
// 法術清單與施法介面的文字來源，不是戰鬥結算的依據。
type SpellSchool byte

const (
	SchoolCleric SpellSchool = iota
	SchoolSorcerer
)

func (s SpellSchool) String() string {
	if s == SchoolSorcerer {
		return "巫師"
	}
	return "牧師"
}

// Spell 是一條法術。
