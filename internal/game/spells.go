// SpellsOf 回傳某一系某一級的法術。
func SpellsOf(school SpellSchool, level int) []Spell {
	var out []Spell
	for _, s := range Spells {
		if s.School == school && s.Level == level {
			out = append(out, s)
		}
	}
	return out
}
